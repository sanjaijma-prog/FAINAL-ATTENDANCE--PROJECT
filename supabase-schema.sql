create table if not exists public.settings (
  key text primary key,
  value jsonb not null
);

create table if not exists public.admins (
  id text primary key,
  username text not null unique,
  name text not null,
  email text not null,
  pass_hash text not null,
  role text not null default 'admin' check (role in ('super','admin')),
  status text not null default 'pending' check (status in ('pending','approved','denied')),
  created_at timestamptz not null default now()
);

create table if not exists public.members (
  id text primary key,
  name text not null,
  eid text not null,
  dept text not null,
  pin_hash text not null,
  manual_edits integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  member_id text not null references public.members(id) on delete cascade,
  date date not null,
  check_in text,
  check_out text,
  counted boolean not null default true,
  updated_at timestamptz not null default now(),
  unique(member_id, date)
);

create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  actor_type text not null,
  actor_id text,
  action text not null,
  member_id text references public.members(id) on delete set null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.daily_logs (
  id bigint generated by default as identity primary key,
  member_id text not null references public.members(id) on delete cascade,
  date date not null,
  task text not null,
  status text not null default 'pending' check (status in ('pending','approved','denied')),
  reviewed_by text,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(member_id, date)
);

create index if not exists idx_daily_logs_status on public.daily_logs(status);
create index if not exists idx_daily_logs_date on public.daily_logs(date);

create table if not exists public.leave_requests (
  id bigint generated by default as identity primary key,
  member_id text not null references public.members(id) on delete cascade,
  from_date date not null,
  to_date date not null,
  reason text not null,
  leave_type text not null default 'planned' check (leave_type in ('planned','emergency')),
  status text not null default 'pending' check (status in ('pending','approved','denied')),
  reviewed_by text,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  check (to_date >= from_date)
);

create index if not exists idx_leave_member on public.leave_requests(member_id);
create index if not exists idx_leave_status on public.leave_requests(status);

create table if not exists public.attendance_marks (
  id bigint generated by default as identity primary key,
  member_id text not null references public.members(id) on delete cascade,
  date date not null,
  type text not null check (type in ('absent','compoff')),
  note text,
  marked_by text,
  created_at timestamptz not null default now(),
  unique(member_id, date)
);

create index if not exists idx_marks_date on public.attendance_marks(date);

create index if not exists idx_attendance_date on public.attendance(date);
create index if not exists idx_attendance_member_date on public.attendance(member_id, date);
create index if not exists idx_activity_created_at on public.activity_logs(created_at desc);
create index if not exists idx_admins_status on public.admins(status);

