-- Run this once in Supabase SQL Editor if your database already exists (adds Absent / Comp-off marks).
create table if not exists public.attendance_marks (
  id bigint generated by default as identity primary key,
  member_id text not null references public.members(id) on delete cascade,
  date date not null,
  type text not null check (type in ('absent','compoff')),
  note text,
  marked_by text,
  created_at timestamptz not null default now(),
  unique(member_id, date)
);

create index if not exists idx_marks_date on public.attendance_marks(date);

alter table public.attendance_marks enable row level security;
